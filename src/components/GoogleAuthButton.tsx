export function GoogleAuthButton({ nextPath }: { nextPath: string }) {
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function onClick() {
    setError(null);
    setLoading(true);
    try {
      localStorage.setItem(LAST_AUTH_KEY, "google");
    } catch {
      /* ignore */
    }
    const supabase = createClient();
    const origin = window.location.origin;
    const { error: oauthError } = await supabase.auth.signInWithOAuth({
      provider: "google",
      options: {
        redirectTo: `${origin}/auth/callback?next=${encodeURIComponent(nextPath)}`,
      },
    });
    if (oauthError) {
      setError(oauthError.message);
      setLoading(false);
    }
  }

  return (
    <div className="space-y-2">
      <button
        type="button"
        className="auth-pill auth-pill-google"
        disabled={loading}
        onClick={() => void onClick()}
      >
        <GoogleGlyph className="auth-pill-icon" />
        {loading ? "Redirecting…" : "Continue with Google"}
      </button>
      {error && (
        <p className="rounded-lg border border-[var(--danger)]/30 bg-[var(--danger)]/10 px-3 py-2 text-sm text-[var(--danger)]">
          {error}
        </p>
      )}
    </div>
  );
}

export { LAST_AUTH_KEY };
